function detectLanguage() {
  const wanted = new URLSearchParams(location.hash.slice(1)).get("lang") || localStorage.getItem("language");
  if (wanted in TEXTS) return wanted;
  return navigator.language.toLowerCase().startsWith("fr") ? "fr" : "en";
}

const language = detectLanguage();
const locale = language === "fr" ? "fr-FR" : "en-GB";

function t(key, values = {}) {
  return TEXTS[language][key].replace(/\{(\w+)\}/g, (_, name) => values[name]);
}

